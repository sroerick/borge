(** Convention dispatch: what a language's project looks like.

    A convention declares the structural rules for a project — file
    extensions, build system, what counts as a "conventional" file, how to
    discover the code units that should each have a spec section, and how to
    build and test.

    DESIGN NOTE (2026-10-26, Phase 0 of docs/convention-abstract.borg):

    The chapter specced a 13-field record. Measuring the tree first showed
    that only three of the nine functions in the old variant API had any
    caller at all (resolve, verify_methods, normalize_section_name), and
    that two of the three Go-specific functions (generate_go_findings,
    write_go_meta_files) were never called from anywhere — meaning Go repos
    were having their .borg.meta generated by the OCAML-dune-aware writer.

    So this record carries only the fields that have a real consumer after
    the refactor. Fields that would be speculative (naming rules, carrier
    syntax, unit nesting) are deliberately absent: they get added by the
    convention that first needs them, not in advance.

    The extension fields are threaded as OPTIONAL arguments elsewhere
    (Surface, Doc_extract, Stats, Code_quality, Book_print) defaulting to
    the OCaml values. That preserves every existing caller byte-for-byte
    while letting a new convention pass its own. It is not the final shape;
    it is the shape that makes a third language possible without a rewrite.

    Comment parsing is SHARED. Borge comments in Go nest the (* *) grammar
    inside Go's /* */ delimiters, so Doc_detect works unchanged for both. *)

(** One discovered code unit: something that should be covered by a section. *)
type code_unit = {
  unit_path : string;   (* the path drift reports *)
  unit_name : string;   (* the name drift compares, already capitalized *)
  unit_kind : string;   (* "unspecified-module" | "unspecified-package" *)
}

type t = {
  name : string;
  (**
     [component_ext] — source file extensions to scan.
     Replaces the hardcoded ".ml" in drift, stats, surface, doc_extract,
     code_quality and book_print.
  *)
  component_ext : string list;
  (**
     [interface_ext] — separate interface files, if the language has them.
     OCaml has .mli; Go does not (export is capitalization).
  *)
  interface_ext : string option;
  (**
     [excluded_dirs] — build output and vendored code, never scanned.
  *)
  excluded_dirs : string list;
  (**
     [conventional_files] — files that need no spec section: build manifests,
     license, README. Feeds Drift.is_conventional_file so a Cargo.toml is not
     reported as an orphan.
  *)
  conventional_files : string list;
  (**
     [index] — discover the code units that each want a section.
     The single seam a new language must implement. Replaces the parallel
     check_code_drift / check_go_code_drift pair.
  *)
  index : string -> code_unit list;
  (**
     [build] and [test] — argv for the CI gate. Replaces the literal
     `dune build` / `dune runtest` in Check.run_worktree.
     Empty means "no gate declared", which is reported, not silently passed.
  *)
  build : string list;
  test : string list;
  (**
     [verify_methods] — vocabulary for (verify ...) stanzas.
  *)
  verify_methods : string list;
}

(** {1 The registry}

    Adding a language is one value plus one line in [all]. If it needs a
    match arm anywhere else, the abstraction is still wrong. *)

(* agent note (|
 *   WHAT: Section "ui-dream" -> "Ui_dream".
 *
 *   WHY: OCaml module names are capitalized snake_case, and drift compares
 *   section names against module names. This is the convention's default
 *   mapping; an explicit (implements ...) in the .borg file overrides it.
 * |) *)
let ocaml_section_to_module name =
  let normalized = String.map (fun c -> if c = '-' then '_' else c) name in
  String.capitalize_ascii normalized

(* agent note (|
 *   WHAT: Discover OCaml modules from dune library stanzas.
 *
 *   WHY: In ocaml-dune the build manifest is the authority on which modules
 *   exist. Scanning lib/*.ml would include files no stanza compiles.
 *   Reproduces the exact paths and names the old check_code_drift emitted
 *   ("lib/<lib>/<mod>.ml", capitalized module) so drift output is unchanged.
 * |) *)
(* agent note (|
 *   WHAT: Normalize a path to repo-relative form ("lib/x/y.ml").
 *
 *   WHY: Drift reports repo-relative paths; dune gives us "./lib". Both
 *   forms must render identically or the report stops being greppable.
 * |) *)
let strip_dot_slash p =
  let n = String.length p in
  if n >= 2 && String.sub p 0 2 = "./" then String.sub p 2 (n - 2) else p

(* agent note (|
 *   WHAT: Module name -> real file path, for one dune library's tree.
 *
 *   WHY: [include_subdirs unqualified] flattens every .ml under a dune
 *   directory into that library, so a module's path is NOT derivable from
 *   the library name. Fabricating "lib/<libname>/<module>.ml" produced
 *   paths that do not exist (lib/borge_lib/book_structure.ml, when the real
 *   file is lib/book/book_structure.ml) — a drift report naming a
 *   nonexistent file is worse than no report, because every finding is
 *   unopenable.
 *
 *   A subdirectory containing its own dune file is a separate library, so
 *   the walk stops there rather than claiming that library's modules too.
 * |) *)
let modules_in_dune_dir dune_dir =
  let rec walk acc d =
    try
      Sys.readdir d
      |> Array.fold_left (fun acc entry ->
        let full = Filename.concat d entry in
        if Sys.is_directory full then
          if Sys.file_exists (Filename.concat full "dune") then acc
          else walk acc full
        else
          match Filename.chop_suffix_opt ~suffix:".ml" entry with
          | Some m -> (m, strip_dot_slash full) :: acc
          | None -> acc
      ) acc
    with Sys_error _ -> acc
  in
  walk [] dune_dir

let ocaml_index dir =
  let dune_files = Dune_parse.parse_all dir in
  List.concat_map (fun df ->
    let dune_dir = Filename.dirname df.Dune_parse.path in
    let table = modules_in_dune_dir dune_dir in
    List.concat_map (function
      | Dune_parse.Library lib ->
          List.map (fun m ->
            let unit_path = match List.assoc_opt m table with
              | Some p -> p
              | None ->
                (* dune says the module exists but no .ml matched. Keep the
                   finding (an unspecced module is still unspecced) but do
                   not invent a plausible-looking path. *)
                Printf.sprintf "%s/%s.ml" (strip_dot_slash dune_dir) m
            in
            { unit_path;
              unit_name = String.capitalize_ascii m;
              unit_kind = "unspecified-module" }
          ) lib.Dune_parse.modules
      | _ -> []
    ) df.Dune_parse.stanzas
  ) dune_files

(* agent note (|
 *   WHAT: Discover Go packages from go.mod + directory layout.
 *
 *   WHY: Go's directory IS the package; there is no manifest listing
 *   modules. Only library packages count — cmd/ executables are entrypoints,
 *   not units that want a section each.
 * |) *)
let go_index dir =
  let project = Go_parse.parse_all dir in
  List.map (fun (pkg : Go_parse.go_package) ->
    { unit_path = pkg.Go_parse.dir_path;
      unit_name = String.capitalize_ascii pkg.Go_parse.package_name;
      unit_kind = "unspecified-package" }
  ) (Go_parse.library_packages project)

