(** {1 Resolution} *)

let default = ocaml_dune

let of_string s =
  List.find_opt (fun c -> c.name = s) all

(* agent note (|
 *   WHAT: Read (convention NAME) from a root .borg file's project form.
 *
 *   WHY: The convention is declared in the spec, not configured outside it —
 *   it is part of what the project claims to be.
 * |) *)
let resolve_from_file path =
  try
    let input = File_utils.read_file path in
    let file = Borge_lang.Parse.parse_file input in
    let rec find_convention = function
      | [] -> default
      | { Borge_lang.Ast.node; _ } :: rest ->
        (match node with
         | Borge_lang.Ast.List (_, children) ->
           let rec scan = function
             | [] -> find_convention rest
             | Borge_lang.Ast.List (_, Borge_lang.Ast.Atom (_, "convention")
                                       :: Borge_lang.Ast.Atom (_, name) :: _) :: _ ->
               (match of_string name with
                | Some t -> t
                | None ->
                  Printf.eprintf
                    "Warning: unknown convention '%s', defaulting to %s\n"
                    name default.name;
                  default)
             | _ :: scan_rest -> scan scan_rest
           in
           scan children
         | _ -> find_convention rest)
    in
    find_convention file.Borge_lang.Ast.top_level
  with _ -> default

let resolve dir =
  match Project.find_roots dir with
  | [] -> default
  | root :: _ -> resolve_from_file root

(** {1 Shared helpers} *)

(* agent note (|
 *   WHAT: Normalize a section name for matching against code.
 *
 *   WHY: "ui-dream" and "ui_dream" must compare equal regardless of
 *   convention. Lowercase + hyphen->underscore is the shared form.
 * |) *)
let normalize_section_name name =
  String.map (fun c -> if c = '-' then '_' else Char.lowercase_ascii c) name

(* agent note (|
 *   WHAT: Does this path have the convention's source extension?
 *
 *   WHY: The one predicate the extension sites need, so each caller does not
 *   re-spell Filename.check_suffix over a hardcoded ".ml".
 * |) *)
let is_component conv path =
  List.exists (fun ext -> Filename.check_suffix path ext) conv.component_ext

let is_interface conv path =
  match conv.interface_ext with
  | None -> false
  | Some ext -> Filename.check_suffix path ext

(* agent note (|
 *   WHAT: Is this directory one the convention says never to scan?
 * |) *)
let is_excluded_dir conv name =
  List.mem name conv.excluded_dirs
