let test_routes_enum () =
  let open Ui_ast in
  let app = {
    theme = None;
    components = [];
    layouts = [];
    pages = [];
    routes = [{ path = "/"; page_name = "home" }; { path = "/dashboard"; page_name = "dashboard" }];
    elements = [];
  } in
  let c = Ui_clay.generate ~source_path:"test.borg" app in
  Alcotest.(check bool) "contains enum page" true (contains c "enum page");
  Alcotest.(check bool) "contains PAGE_HOME" true (contains c "PAGE_HOME");
  Alcotest.(check bool) "contains layout_app switch" true (contains c "layout_app")

let test_header_file () =
  let open Ui_ast in
  let app = {
    theme = None;
    components = [{ name = "button"; properties = [P_interactive Interactive_click]; slots = []; children = []; variants = [] }];
    layouts = [];
    pages = [];
    routes = [{ path = "/"; page_name = "home" }];
    elements = [];
  } in
  let h = Ui_clay.generate_header_file app in
  Alcotest.(check bool) "contains include guard" true (contains h "#ifndef UI_APP_H");
  Alcotest.(check bool) "contains render_button declaration" true (contains h "render_button");
  Alcotest.(check bool) "contains enum page" true (contains h "enum page")
;;

let () =
  Alcotest.run "ui_clay" [
    "ui_clay", [
      Alcotest.test_case "simple element" `Quick test_simple_element;
      Alcotest.test_case "color RGBA" `Quick test_color_rgba;
      Alcotest.test_case "keyword color" `Quick test_keyword_color;
      Alcotest.test_case "C sanitization" `Quick test_c_sanitization;
      Alcotest.test_case "routes enum" `Quick test_routes_enum;
      Alcotest.test_case "header file" `Quick test_header_file;
    ];
  ]
