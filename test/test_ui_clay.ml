(* Test ui_clay generator *)
open Borge_lib

let contains haystack needle =
  (* exempt: Str.search_forward *)
  try let _ = Str.search_forward (Str.regexp_string needle) haystack 0 in true
  with Not_found -> false

let test_simple_element () =
  let open Ui_ast in
  let app = {
    theme = None;
    components = [];
    layouts = [];
    pages = [];
    routes = [];
    elements = [
      { name = Some "box";
        properties = [P_layout Vertical; P_width (Flex 1); P_bg (Hex "#333")];
        children = [];
        variants = []; text = None;
      };
    ];
  } in
  let c = Ui_clay.generate ~source_path:"test.borg" app in
  Alcotest.(check bool) "contains CLAY_CONTAINER" true (contains c "CLAY_CONTAINER");
  Alcotest.(check bool) "contains TOP_TO_BOTTOM" true (contains c "CLAY_TOP_TO_BOTTOM");
  Alcotest.(check bool) "contains SIZING_GROW" true (contains c "CLAY_SIZING_GROW");
  Alcotest.(check bool) "contains background RGBA" true (contains c "backgroundColor");
  Alcotest.(check bool) "contains header" true (contains c "Generated by borge generate")

