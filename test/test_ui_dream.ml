(* Test ui_dream generator *)
open Borge_lib

let contains haystack needle =
  (* exempt: Str.search_forward *)
  try let _ = Str.search_forward (Str.regexp_string needle) haystack 0 in true
  with Not_found -> false

let test_simple_element () =
  let open Ui_ast in
  let app = {
    theme = None;
    components = [];
    layouts = [];
    pages = [];
    routes = [];
    elements = [
      { name = Some "box";
        properties = [P_layout Vertical; P_width (Flex 1); P_bg (Hex "#333")];
        children = [];
        variants = []; text = None;
      };
    ];
  } in
  let ml = Ui_dream.generate ~source_path:"test.borg" app in
  Alcotest.(check bool) "contains flex-col" true (contains ml "flex-col");
  Alcotest.(check bool) "contains flex: 1" true (contains ml "flex: 1");
  Alcotest.(check bool) "contains background-color" true (contains ml "background-color");
  Alcotest.(check bool) "contains header" true (contains ml "Generated by borge generate")

