      Radius_entry ("sm", 4);
    ] };
    components = [];
    layouts = [];
    pages = [];
    routes = [];
    elements = [
      { name = Some "box";
        properties = [P_bg (Palette "bg-primary"); P_padding (Padding_uniform (Spacing_var "md"))];
        children = [];
        variants = []; text = None;
      };
    ];
  } in
  let ml = Ui_dream.generate ~source_path:"test.borg" app in
